    assert.match(pipelineSource, /const authoritativeTask = await executeAuthoritativeAnalysisPath\(/)
    assert.match(pipelineSource, /runPdfServer: \(\) => tryFastServerPdfAnalyze\(/)
    assert.match(pipelineSource, /runImageServer: \(\) => tryFastServerImageAnalyze\(/)
