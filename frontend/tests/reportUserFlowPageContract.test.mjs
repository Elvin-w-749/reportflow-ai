    assert.match(uploadSource, /active = saveActiveAnalysisTask\(/)
    assert.match(uploadSource, /onUnload\(\(\) => \{[\s\S]*analysisAbortController\?\.abort\?\.\(\)/)
    assert.match(uploadSource, /e\.terminalAnalysisFailure === true/)
		assert.match(pipelineSource, /createTerminalAnalysisFailure\(terminal, remoteJob\.jobId\)/)
		assert.match(uploadSource, /const acknowledgeTerminalAnalysisFailure = async \(jobId, supportRef\) =>/)
		assert.match(uploadSource, /if \(acknowledged\) clearActiveAnalysisTask\(id\)/)
