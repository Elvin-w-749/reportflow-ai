    assert.doesNotMatch(manageSource, /row\?\.analysisData\?\.aiInsight\?\.total_score/)
    assert.doesNotMatch(manageSource, /row\?\.analysisResult\?\.report\?\.totalScore/)
    assert.doesNotMatch(reportStorageSource, /ad\?\.aiInsight\?\.risk_level/)
